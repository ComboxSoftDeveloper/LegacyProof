namespace LegacyProof.Types;

/// <summary>
/// Наследник без единой строки. Ничего не переопределяет, ничего не добавляет.
///
/// Конструктор Random проверяет, не унаследовались ли от него, и для потомков
/// включает старую реализацию — чтобы переопределённые методы вызывались так же,
/// как вызывались раньше. Проверка срабатывает даже на пустом наследнике.
/// </summary>
internal sealed class EmptyRandom : Random
{
}

/// <summary>
/// Такой же пустой наследник, но с начальным значением: конструктор базового
/// типа вызывается с числом.
/// </summary>
internal sealed class SeededRandom : Random
{
    /// <summary>Передаёт начальное значение базовому типу.</summary>
    internal SeededRandom(int seed) : base(seed)
    {
    }
}
